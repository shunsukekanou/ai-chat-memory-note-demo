// お試し用の見本データ。完全に架空の日常相談・仕事相談（実在の人・会社・出来事は入っていない）。
import { uid, type Chat, type Note } from './types'

const d = (y: number, m: number, day: number, h = 20) => new Date(y, m - 1, day, h, 0, 0).getTime()

export function sampleData(): { chats: Chat[]; notes: Note[] } {
  const c = (source: Chat['source'], title: string, date: number, pairs: [string, string][], summarized = false): Chat => ({
    id: uid(),
    source,
    title,
    date,
    summarized,
    sample: true,
    messages: pairs.flatMap(([u, a]) => [
      { role: 'user' as const, text: u },
      { role: 'ai' as const, text: a },
    ]),
  })
  const kondate = c('gemini', '平日の夕食の献立を考えたい', d(2026, 10, 3), [
    ['平日の夕食の献立を相談したい。仕事から帰って30分以内で作れるものがいい。辛いものは苦手。', '30分以内なら、鶏むね肉の塩レモン焼きや、豆腐と野菜の味噌炒めはどうでしょう。辛さは使わない味付けにします。'],
    ['予算は、1週間で5000円くらいにしたい。', '週5000円なら、鶏むね肉・豆腐・卵・旬の野菜を中心にすると収まります。週末にまとめて下ごしらえをすると、平日が楽になります。'],
    ['じゃあ、月曜は鶏むね肉、火曜は豆腐の炒めものにする。', '決まりです。月曜：鶏むね肉の塩レモン焼き、火曜：豆腐と野菜の味噌炒め。水曜以降も続けて考えますか？'],
  ])
  const kaigi = c('chatgpt', '週次会議の資料の書き方', d(2026, 10, 12), [
    ['週次会議の資料を作っている。いつも長くなってしまう。どう直せばいい？', 'まず結論を1行目に書き、根拠を3つまでに絞ると短くなります。A4 1枚に収めるのを目安にしてください。'],
    ['数字は出典を付けたい。見出しは短くしたい。', '数字には、出典と日付を括弧で添えましょう。見出しは10文字前後が読みやすいです。'],
    ['わかった。次回から、結論を先に、A4 1枚で作る。', 'いい方針です。最初の1行に「今週の結論」を置くテンプレートを作っておくと、毎回楽になります。'],
  ])
  const hikkoshi = c(
    'claude',
    '引っ越しの手続きの段取り',
    d(2026, 10, 20),
    [
      ['11月末に引っ越す予定。手続きの順番を整理したい。', '先に、電気・ガス・水道の停止と開始の連絡をします。つぎに、役所の手続きと、郵便の転送届です。'],
      ['荷造りは土日にまとめてやりたい。平日は時間がない。', '土日で、使わないものから箱に詰めるのがおすすめです。台所用品は最後にします。'],
    ],
    true,
  )
  const shinjin = c('gemini', '新人への仕事の教え方', d(2026, 11, 2), [
    ['新人に作業を教えるとき、一度に全部言ってしまう。どうすれば伝わる？', '一度に教えるのは1つにして、やって見せたあとに、本人にやってもらいます。最後に、1行の復習メモを書いてもらうと定着します。'],
    ['専門用語が多いと言われた。', '専門用語には、初出のときに言い換えを添えましょう。例：「段取り替え（次の仕事の準備）」。'],
  ])
  const pc = c('chatgpt', 'ノートパソコン選び', d(2026, 11, 8), [
    ['ノートパソコンを買い替えたい。持ち歩くので軽いほうがいい。', '持ち歩くなら、1.2kg以下で、画面は14インチ前後が扱いやすいです。電池は10時間以上を目安にしてください。'],
    ['予算は15万円まで。写真の整理も少しする。', '15万円なら、メモリ16GBのモデルが狙えます。写真の整理には、画面の色がきれいなものが向いています。'],
  ])
  const chats = [kondate, kaigi, hikkoshi, shinjin, pc]
  const n = (kind: Note['kind'], text: string, pinned: boolean, chat?: Chat): Note => ({
    id: uid(),
    kind,
    text,
    pinned,
    chatId: chat?.id,
    createdAt: chat?.date ?? d(2026, 11, 1),
    sample: true,
  })
  const notes: Note[] = [
    n('memory', '引っ越しは11月末の予定。電気・ガス・水道の連絡を先にし、そのあと役所の手続きと郵便の転送届をする段取りにした。', false, hikkoshi),
    n('memory', '荷造りは土日にまとめて行い、使わないものから詰める。台所用品は最後。', false, hikkoshi),
    n('rule', '土日にまとめて作業し、平日は手間をかけない進め方が好み。', false, hikkoshi),
    n('rule', '結論を先に、短く答えてほしい。', true),
    n('rule', '専門用語は、使う前に言い換える。', true),
  ]
  return { chats, notes }
}
